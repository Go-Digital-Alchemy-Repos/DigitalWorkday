export const THEME_PACK_MAP = new Map<string, ThemePack>(
  THEME_PACKS.map((p) => [p.id, p])
);

export const PRIMARY_THEME_PACK_IDS = ["light", "dark", "anthropic", "huly", "asana"] as const satisfies readonly PrimaryThemePackId[];

export type PrimaryThemePack = ThemePack & { id: PrimaryThemePackId };

export const PRIMARY_THEME_PACKS: PrimaryThemePack[] = PRIMARY_THEME_PACK_IDS.map(
  (id) => THEME_PACK_MAP.get(id)! as PrimaryThemePack
);

export function normalizeThemePackId(id: string | null | undefined): PrimaryThemePackId {
  if (!id) return "light";
  if (id === "system") return "light";

  if ((PRIMARY_THEME_PACK_IDS as readonly string[]).includes(id)) {
    return id as PrimaryThemePackId;
  }

  const pack = THEME_PACK_MAP.get(id);
  if (!pack) return "light";
  return pack.kind === "dark" ? "dark" : "light";
}

export function getThemePack(id: string): ThemePack {
  const normalizedId = normalizeThemePackId(id);
  return THEME_PACK_MAP.get(normalizedId) ?? THEME_PACK_MAP.get("light")!;
}

export function resolveThemePackId(
  userOverride: string | null | undefined,
  tenantDefault: string | null | undefined
): string {
  if (userOverride) return normalizeThemePackId(userOverride);
  if (tenantDefault) return normalizeThemePackId(tenantDefault);
  return "light";
}
